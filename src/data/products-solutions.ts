export interface SolutionCard {
  idx: string;
  /** 卡片配图（文字主导的卡片可不带） */
  img?: string;
  alt?: string;
  title: string;
  desc: string;
  tag?: string;
  /** 文字要点列表（标题 + 描述），有则底部显示各项标题胶囊 */
  list?: { title: string; desc?: string }[];
  /** 要点列表列数（1 = 纵向单列；缺省沿用分组布局） */
  listCols?: 1 | 2;
  /** 金色方块引导的价值指标行 */
  metric?: string;
  /** 产品详情页链接（暂无独立详情页的产品不带链接） */
  href?: string;
}

/** 产品分组：一个业务场景及其归属产品 */
export interface ProductGroup {
  /** 分组块锚点 id */
  id: string;
  /** 所属场景名（与顶部三大业务场景卡一致） */
  scene: string;
  /** 场景英文标签 */
  sceneEn: string;
  /** 场景简介（分组标题下的层级说明） */
  desc: string;
  /** 列数覆盖（1 = 通栏纵向排列）；缺省按组内产品数自动排布 */
  columns?: 1 | 2 | 3;
  /** 该场景下的产品与方案 */
  products: SolutionCard[];
}

